/** @typedef {{ en: string, zh: string }} BiOpt */

/** @param {BiOpt} item */
export function bilingualLabel(item) {
  return `${item.zh}(${item.en})`;
}

/** @param {BiOpt[]} list @param {string} en */
export function findOption(list, en) {
  return list.find((item) => item.en === en) || null;
}

/** @param {BiOpt[]} list @param {string} en @param {'en'|'zh'} lang */
export function optionText(list, en, lang = 'en') {
  const found = findOption(list, en);
  if (!found) return en || '';
  return lang === 'zh' ? found.zh : found.en;
}

